#!/usr/bin/env bash
# Regenerates apps/desktop/src-tauri/THIRD-PARTY-LICENSES.txt, the license
# file that ships inside every distributed package and backs the in-app
# viewer (Settings > About > Third-party Licenses).
#
# Sources, so the output cannot drift from what actually ships:
#   1. Rust components    — cargo about (about.toml / about.hbs), Cargo.lock
#   2. JavaScript parts   — scripts/generate-licenses-js.mjs, pnpm-lock.yaml
#   3. Bundled components — scripts/third-party-assets-licenses.txt
#      (hand-maintained: mihomo binary, geo data, subset font, vendored lib)
#
# Prerequisites: cargo-about on PATH (https://github.com/EmbarkStudios/
# cargo-about), a Rust toolchain, Node.js and pnpm, and `pnpm install`
# already run for the workspace.
set -euo pipefail

cd "$(dirname "$0")/.."
OUT="apps/desktop/src-tauri/THIRD-PARTY-LICENSES.txt"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

cargo about generate --fail about.hbs -o "$TMP/rust-raw.txt"
node scripts/generate-licenses-js.mjs "$TMP/js.txt"

# cargo about also gathers the workspace's own crates. They are not
# third-party components, so drop their index lines; fail loudly if the
# rendered format ever changes and the lines stop matching. Match the
# crates by name only: the release workflow rewrites the desktop crate's
# version to the release tag before this script runs, so a filter pinned
# to one version would stop matching and fail every release.
# The format check must run on the raw output: checking the filtered
# file could never trip, because the filter already removed the very
# lines it looks for.
if ! grep -q -E -e '^  \* (Zephyr|zephyr-core|zephyr-core-ffi) ' "$TMP/rust-raw.txt"; then
    echo "error: first-party crates not found in cargo-about output; its index format may have changed" >&2
    exit 1
fi
grep -v -E -e '^  \* (Zephyr|zephyr-core|zephyr-core-ffi) [^ ]+' \
    "$TMP/rust-raw.txt" > "$TMP/rust.txt"
if grep -q -E -e '^  \* (Zephyr|zephyr-core|zephyr-core-ffi) ' "$TMP/rust.txt"; then
    echo "error: first-party crates still present in generated licenses" >&2
    exit 1
fi

{
    cat << 'HEADER'
THIRD-PARTY LICENSES

Zephyr is distributed with the open-source components listed below. This
file reproduces the full license text of every component, as the licenses
require for binary distribution. It is generated by
scripts/generate-licenses.sh — Parts 1 and 2 from the workspace
lockfiles, Part 3 maintained by hand; do not edit it by hand.

Contents
  Part 1 — Rust components (crates compiled into the app)
  Part 2 — JavaScript components (packages bundled into the app)
  Part 3 — Bundled components and other materials (proxy core binary,
           geo data files, subset font, vendored library, build-time
           tool whose generated output ships, and a JavaScript package
           that ships no license text files of its own)

For components under the MPL-2.0 (listed in Part 1): the crates are used
unmodified, and the corresponding source code is available from each
crate's repository, linked in the Part 1 component index.

For the components under the GNU GPL v3.0 (Part 3 — the mihomo proxy
core binary and the geo data files): the source code is maintained in
the open in the upstream repositories linked there, which is where the
corresponding source can be obtained. The exact mihomo version of any
installed copy is shown in Settings > About.

======================================================================
PART 1 — RUST COMPONENTS
======================================================================

HEADER
    # The cargo-about template output carries its own section banner;
    # strip everything up to its "PART A" so the parts nest cleanly.
    sed -n '/^PART A/,$p' "$TMP/rust.txt"
    echo
    cat "$TMP/js.txt"
    echo
    cat scripts/third-party-assets-licenses.txt
} > "$TMP/assembled.txt"

# Some upstream license files use CRLF endings. Normalize to LF so the
# generated file is byte-identical on every platform (and matches the
# repository's line-ending rules), whichever machine regenerates it.
# Use tr rather than sed: BSD sed (macOS release runners) does not treat
# \r in a pattern as a carriage return.
tr -d '\r' < "$TMP/assembled.txt" > "$OUT"

echo "Regenerated $OUT"
