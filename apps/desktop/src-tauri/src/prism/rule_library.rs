        let path = directory.path().join("source.prism.yaml");
        let alias = directory.path().join("local.prism.yaml");
        let original = "rules: []\n";
        let replacement = "rules: ['MATCH,DIRECT']\n";
        std::fs::write(&path, original).unwrap();
        std::os::unix::fs::symlink(&path, &alias).unwrap();
        let generated = std::collections::HashSet::new();
        let target = resolve_rule_save_target(&alias, directory.path(), &generated).unwrap();
