// Compare-and-save also excludes creation, deletion and rename of the same file.
static RULE_FILE_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

pub(super) fn lock_rule_files() -> Result<std::sync::MutexGuard<'static, ()>, String> {
    RULE_FILE_LOCK
        .lock()
        .map_err(|error| format!("Rule file lock poisoned: {error}"))
}

pub(crate) fn generated_rule_files(
    state: &PrismState,
) -> Result<std::collections::HashSet<String>, String> {
    use super::overrides::{OverrideExt, OverrideItem};
    let meta = super::overrides::load_meta(state)?;
    Ok(meta
        .items
        .iter()
        .filter(|item| item.ext == OverrideExt::PrismYaml)
        .map(OverrideItem::patch_filename)
        .collect())
}

pub(crate) fn ensure_user_rule(state: &PrismState, filename: &str) -> Result<(), String> {
    let normalized = sanitize_filename(filename)?;
    let directory = state.get_prism_workspace()?;
    if addresses_generated_file(&directory, &normalized, &generated_rule_files(state)?) {
        return Err(
            "This rule file is generated by an override. Edit the owning override instead."
                .to_owned(),
        );
    }
    Ok(())
}

fn addresses_generated_file(
    directory: &std::path::Path,
    filename: &str,
    generated: &std::collections::HashSet<String>,
) -> bool {
    GeneratedRuleNames::new(directory, generated).contains(directory, filename)
}

struct GeneratedRuleNames<'a> {
    exact: &'a std::collections::HashSet<String>,
    folded: std::collections::HashSet<String>,
    paths: std::collections::HashSet<std::path::PathBuf>,
}

impl<'a> GeneratedRuleNames<'a> {
    fn new(directory: &std::path::Path, exact: &'a std::collections::HashSet<String>) -> Self {
        Self {
            exact,
            folded: exact.iter().map(|name| name.to_ascii_lowercase()).collect(),
            paths: exact
                .iter()
                .filter_map(|name| directory.join(name).canonicalize().ok())
                .collect(),
        }
    }

    fn contains(&self, directory: &std::path::Path, filename: &str) -> bool {
        if self.exact.contains(filename) {
            return true;
        }
        if self.contains_path(&directory.join(filename)) {
            return true;
        }
        // Missing patches cannot be canonicalized. Probe this directory's own
        // name resolution only for a case-equivalent metadata reservation.
        self.folded.contains(&filename.to_ascii_lowercase())
            && directory_ignores_ascii_case(directory)
    }

    fn contains_path(&self, path: &std::path::Path) -> bool {
        path.canonicalize()
            .is_ok_and(|target| self.paths.contains(&target))
    }
}

fn directory_ignores_ascii_case(directory: &std::path::Path) -> bool {
    let Ok(probe) = tempfile::Builder::new()
        .prefix(".zephyr-case-")
        .tempfile_in(directory)
    else {
        // A name-equivalent reservation stays protected if the volume cannot
        // be inspected. Ordinary unrelated rule names remain unaffected.
        return true;
    };
    let Some(name) = probe.path().file_name().and_then(|name| name.to_str()) else {
        return true;
    };
    directory
        .join(name.to_ascii_uppercase())
        .try_exists()
        .unwrap_or(true)
}

/// A rule file name is taken by the file itself or by its disabled copy
/// (`<name>.disabled`), which the library lists under the same name.
pub(super) fn name_taken(path: &std::path::Path) -> Result<bool, String> {
    let mut parked = path.as_os_str().to_owned();
    parked.push(".disabled");
    for candidate in [path, std::path::Path::new(&parked)] {
        match std::fs::symlink_metadata(candidate) {
            Ok(_) => return Ok(true),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => return Err(format!("Failed to inspect rule filename: {error}")),
        }
    }
    Ok(false)
}

/// Every rule-file producer respects metadata reservations even when a disabled
/// override has removed its generated patch from disk.
async fn publish_rule_file(
    app: tauri::AppHandle,
    filename: String,
    content: String,
) -> Result<String, String> {
    tokio::task::spawn_blocking(move || {
        let safe_content = sanitize_rule_yaml(&content)?;
        let _config = crate::prism::pipeline::RUN_CONFIG_LOCK
            .lock()
            .map_err(|error| format!("Run config lock poisoned: {error}"))?;
        let state = tauri::Manager::state::<PrismState>(&app);
        ensure_user_rule(&state, &filename)?;
        let path = state.get_prism_workspace()?.join(&filename);
        let _files = lock_rule_files()?;
        if name_taken(&path)? {
            return Err(format!("Rule file '{filename}' already exists"));
        }
        crate::core_manager::core::secure_io::write_file_secure_atomic(&path, &safe_content)?;
        Ok(filename)
    })
    .await
    .map_err(|error| format!("Rule creation task failed: {error}"))?
}

#[tauri::command]
pub fn open_prism_folder(state: State<PrismState>) -> Result<String, String> {
    let prism_dir = state.get_prism_workspace()?;

    tauri_plugin_opener::open_path(&prism_dir, None::<&str>)
        .map_err(|e| format!("Failed to open prism folder: {e}"))?;

    Ok(prism_dir.to_string_lossy().into_owned())
}

#[tauri::command]
pub fn rule_list(state: State<PrismState>) -> Result<Vec<RuleFileInfo>, String> {
    let prism_dir = state.get_prism_workspace()?;
    // Listing stays useful with broken override metadata; mutation guards
    // still propagate the metadata error and all uncertain entries are read-only.
    let generated = generated_rule_files(&state).ok();
    let reserved = generated
        .as_ref()
        .map(|names| GeneratedRuleNames::new(&prism_dir, names));
    let entries =
        std::fs::read_dir(&prism_dir).map_err(|e| format!("Failed to read prism dir: {e}"))?;

    let mut files = Vec::new();
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        // Disabled files are renamed to `<name>.prism.yaml.disabled`; list them
        // under their base name so the library can show and re-enable them.
        let enabled = !name.ends_with(".disabled");
        let base = name.strip_suffix(".disabled").unwrap_or(&name).to_owned();
        if base.ends_with(".prism.yaml") {
            let content = std::fs::read_to_string(entry.path()).unwrap_or_default();
            files.push(RuleFileInfo {
                read_only: reserved.as_ref().is_none_or(|names| {
                    names.contains(&prism_dir, &base) || names.contains_path(&entry.path())
                }),
                filename: base,
                rule_count: count_rules(&content),
                source: detect_source(&content).to_owned(),
                enabled,
            });
        }
    }
    // `foo.prism.yaml` next to a stale `foo.prism.yaml.disabled` is one file: list it
    // once, as the enabled copy the compiler actually reads.
    files.sort_by(|a, b| a.filename.cmp(&b.filename).then(b.enabled.cmp(&a.enabled)));
    files.dedup_by(|later, first| later.filename == first.filename);
    Ok(files)
}

#[tauri::command]
pub fn rule_read(state: State<PrismState>, filename: String) -> Result<String, String> {
    let prism_dir = state.get_prism_workspace()?;
    let path = resolve_rule_path(&prism_dir, &filename)?;
    std::fs::read_to_string(&path).map_err(|e| format!("Failed to read rule file: {e}"))
}

/// Sanitize user-supplied rule YAML before it is written to disk.
///
/// - Content that does not parse as YAML is rejected outright (fail closed,
///   the same behaviour as `rule_import_text`) instead of being saved raw.
/// - Every parsed root has its dangerous keys stripped, including keys
///   nested in a root sequence or a tagged root: mihomo's decoder resolves
///   tags and reads those nested mappings, so they must not bypass
///   sanitization (the rule import paths clean every root type as well).
///   If nothing was removed, the original text is kept verbatim so
///   comments and formatting survive, which also keeps empty files and
///   plain scalars as-is.
fn sanitize_rule_yaml(content: &str) -> Result<String, String> {
    let value = match serde_yaml::from_str::<serde_yaml::Value>(content) {
        Ok(value) => value,
        Err(e) => return Err(format!("Invalid YAML: {e}")),
    };
    let mut sanitized = value.clone();
    remove_dangerous_keys(&mut sanitized, false);
    if sanitized == value {
        Ok(content.to_owned())
    } else {
        serde_yaml::to_string(&sanitized)
            .map_err(|e| format!("Failed to serialize sanitized YAML: {e}"))
    }
}

