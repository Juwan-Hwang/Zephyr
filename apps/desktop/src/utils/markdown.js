/**
 * Convert a subset of Markdown to safe HTML.
 * Automatically strips the "📦 下载说明" / "Download" section.
 * @param {string} md - Raw Markdown text
 * @returns {string} HTML string
 */
export function markdownToHtml(md) {
    // --- Pre-processing: strip unwanted sections ---

    // Remove "📦 下载说明" / "Download" section and everything after it
    let processed = md.replace(/(?:^|\n)##\s*📦?\s*下载说明[\s\S]*$/i, '');
    processed = processed.replace(/(?:^|\n)##\s*📦?\s*Download[\s\S]*$/i, '');

    // --- Token-level processing (order matters) ---

    const PH = pickSentinel(processed);
    // No free delimiter (pathological input): show the text unformatted
    // rather than dropping or misreading any of it.
    if (PH === null) {
        return sanitizeHtml(`<p class="text-xs text-[var(--text-secondary)] leading-relaxed my-2">${escapeHtml(processed.trim())}</p>`);
    }
    let html = processed;

    // Use placeholders for code blocks and inline code so that
    // escapeHtml in subsequent steps doesn't double-escape the generated HTML tags.
    /** @type {string[]} */
    const placeholders = [];

    // 1. Code blocks (```...```) — must be first to prevent inner content from being parsed
    html = html.replace(/```(\w*)\n([\s\S]*?)```/g, (_, _lang, code) => {
        const idx = placeholders.length;
        placeholders.push(`<pre class="bg-[var(--zephyr-bg-input)] rounded-lg p-3 my-3 text-xs overflow-x-auto leading-relaxed"><code>${escapeHtml(code.trimEnd())}</code></pre>`);
        return `${PH}CODEBLOCK_${idx}${PH}`;
    });

    // 2. Inline code — before bold/italic to avoid matching inside code
    /** @type {string[]} the code as written, by placeholder index */
    const codeText = [];
    html = html.replace(/`([^`]+)`/g, (_, code) => {
        const idx = placeholders.length;
        codeText[idx] = code;
        placeholders.push(`<code class="bg-[var(--zephyr-bg-input)] px-2 py-0.5 rounded text-xs align-middle">${escapeHtml(code)}</code>`);
        return `${PH}INLINECODE_${idx}${PH}`;
    });

    // 3. Escape HTML once globally — prevents XSS and avoids nested-formatting bugs
    //    where escapeHtml inside individual replacements would escape HTML tags
    //    generated by earlier replacements (e.g. *italic **bold** text*).
    html = escapeHtml(html);

    // 3b. Link and image targets: kept out of the emphasis passes below, so a
    //     URL with `*`, `**` or `~~` in it keeps its address. Resolved again
    //     by the image and link passes. Only a `(…)` after a `[…]` is one: in
    //     other text a `](` is just text, and its emphasis still applies.
    /** @type {string[]} */
    const hrefs = [];
    // A `(…)` that holds a fenced code block is no link target: leave it as
    // text, so the block is restored where it stands instead of being
    // folded into an address.
    /** @param {string} target */
    const holdsBlock = (target) => target.includes(`${PH}CODEBLOCK_`);
    html = html.replace(/(\[[^\]]*\])\(([^)]+)\)/g, (match, label, href) => {
        if (holdsBlock(href)) return match;
        hrefs.push(href);
        return `${label}(${PH}HREF_${hrefs.length - 1}${PH})`;
    });
    /** @param {string} ref */
    const realHref = (ref) => {
        const tag = `${PH}HREF_`;
        if (!ref.startsWith(tag) || !ref.endsWith(PH)) return ref;
        const href = hrefs[Number(ref.slice(tag.length, -PH.length))] ?? '';
        // Backticks in a URL are part of the address, not inline code.
        return href.split(PH).map((part, i) => {
            if (i % 2 === 0) return part;
            const code = codeText[Number.parseInt(part.slice(part.indexOf('_') + 1), 10)];
            return code === undefined ? '' : escapeHtml(`\`${code}\``);
        }).join('');
    };

    // 4. Headings (h1 > h2 > h3 to avoid h3 regex matching h2/h1)
    html = html.replace(/^### (.+)$/gm, (_, t) => `<h4 class="text-sm font-semibold text-[var(--text-primary)] mt-4 mb-1">${t}</h4>`);
    html = html.replace(/^## (.+)$/gm, (_, t) => `<h3 class="text-base font-semibold text-[var(--text-primary)] mt-5 mb-2">${t}</h3>`);
    html = html.replace(/^# (.+)$/gm, (_, t) => `<h2 class="text-lg font-bold text-[var(--text-primary)] mt-5 mb-2">${t}</h2>`);

    // 5. Blockquotes
    html = html.replace(/^&gt; (.+)$/gm, (_, t) => `<blockquote class="border-s-2 border-accent/40 ps-3 my-2 text-xs text-[var(--text-secondary)] italic">${t}</blockquote>`);

    // 6. Bold (before italic to avoid ** being partially consumed)
    html = html.replace(/\*\*(.+?)\*\*/g, (_, t) => `<strong class="font-semibold text-[var(--text-primary)]">${t}</strong>`);

    // 7. Italic
    html = html.replace(/(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)/g, (_, t) => `<em>${t}</em>`);

    // 8. Strikethrough (~~text~~)
    html = html.replace(/~~(.+?)~~/g, (_, t) => `<del class="line-through text-[var(--text-muted)]">${t}</del>`);

    // 9. Horizontal rules
    html = html.replace(/^---$/gm, '<hr class="border-[var(--zephyr-border-default)] my-4">');

    // 10. Images — show alt text only (no actual img tag for security)
    html = html.replace(/!\[([^\]]*)\]\([^)]+\)/g, (_, alt) => `<span class="text-xs text-[var(--text-muted)]">[${alt}]</span>`);

    // 11. Links
    html = html.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (match, text, ref) => {
        if (holdsBlock(ref)) return match;
        const href = realHref(ref);
        // Block dangerous URI schemes
        if (/^\s*(javascript|vbscript|data)\s*:/i.test(href)) {
            return `<span class="text-xs text-[var(--text-secondary)]">${text}</span>`;
        }
        // Skip mailto links — show email as plain text
        if (href.startsWith('mailto:')) {
            return `<span class="text-xs text-[var(--text-secondary)]">${href.replace(/^mailto:/, '')}</span>`;
        }
        // href is already HTML-escaped from the initial escapeHtml pass;
        // only need to escape quotes for attribute context (avoid double-escaping &amp;)
        const safeHref = href.replace(/"/g, '&quot;').replace(/'/g, '&#39;');
        return `<a href="${safeHref}" class="text-accent underline" target="_blank" rel="noopener">${text}</a>`;
    });

    // 12. Unordered lists
    html = html.replace(/^(\s*)[-*] (.+)$/gm, (_, indent, t) => `${indent}<li class="ms-4 list-disc text-xs text-[var(--text-secondary)] leading-relaxed py-0.5">${t}</li>`);
    html = html.replace(/((?:<li[^>]*>.*<\/li>\n?)+)/g, '<ul class="my-3 space-y-2">$1</ul>');

    // 13. Ordered lists
    html = html.replace(/^\d+\. (.+)$/gm, (_, t) => `<li class="ms-4 list-decimal text-xs text-[var(--text-secondary)] leading-relaxed py-0.5">${t}</li>`);

    // 14. Paragraphs: wrap remaining loose lines unless they already start with
    // a block element produced above or a code block placeholder. Lines that
    // start with inline markup (<strong>, <a>, ...) still get the wrapper.
    html = html.split('\n').map((line) => {
        const lead = line.trimStart();
        if (lead === '' || /^<\/?(?:h[2-4]|blockquote|hr|ul|li)\b/.test(lead) || lead.startsWith(`${PH}CODEBLOCK`)) return line;
        return `<p class="text-xs text-[var(--text-secondary)] leading-relaxed my-2">${line}</p>`;
    }).join('\n');

    // --- Restore placeholders (before sanitizeHtml) ---
    // PH occurs only in placeholders, so after splitting on it every odd part
    // is a placeholder name ("CODEBLOCK_3" / "INLINECODE_7").
    /** @type {(text: string) => string} */
    const restore = (text) => text.split(PH).map((part, i) => {
        if (i % 2 === 0) return part;
        // A target that no link or image pass used goes back as written,
        // with the inline code inside it restored too.
        if (part.startsWith('HREF_')) return restore(hrefs[Number.parseInt(part.slice(5), 10)] ?? '');
        return placeholders[Number.parseInt(part.slice(part.indexOf('_') + 1), 10)] ?? '';
    }).join('');
    html = restore(html);

    // --- Post-processing ---
    html = html.replace(/\n{3,}/g, '\n\n');

    return sanitizeHtml(html.trim());
}

