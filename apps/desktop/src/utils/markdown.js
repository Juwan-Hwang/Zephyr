/**
 * Lightweight Markdown → HTML converter (subset).
 *
 * Supports: headings, bold, italic, strikethrough, code blocks, inline code,
 * blockquotes, unordered/ordered lists, links, horizontal rules, images.
 *
 * Inspired by a CLI markdown renderer but adapted for browser HTML output.
 * Zero external dependencies.
 */

import { escapeHtml, sanitizeHtml } from './sanitize.js';

/**
 * Pick one private-use character absent from the input to delimit code
 * placeholders, so no input text is altered or mistaken for a placeholder.
 * One pass over the input; returns null only if every BMP private-use
 * character (U+E000–U+F8FF) occurs in it.
 * @param {string} text
 * @returns {string | null}
 */
function pickSentinel(text) {
    const seen = new Uint8Array(0xF900 - 0xE000);
    for (let i = 0; i < text.length; i++) {
        const code = text.codePointAt(i) ?? 0;
        if (code >= 0xE000 && code <= 0xF8FF) seen[code - 0xE000] = 1;
    }
    const free = seen.indexOf(0);
    return free === -1 ? null : String.fromCodePoint(0xE000 + free);
}

