/**
 * Check whether a language code is right-to-left.
 * @param {string} lang - ISO 639-1 language code.
 * @returns {boolean}
 */
export function isRTL(lang) {
    return ['ar', 'he', 'fa', 'ur'].includes((lang || '').split('-')[0].toLowerCase());
}

